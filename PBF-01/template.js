// Menyimpan nama depan ke dalam variabel firstName
let firstName = 'Cristiano';

// Menyimpan nama belakang ke dalam variabel lastName
let lastName = 'Ronaldo';

// Meminta pengguna memasukkan umur melalui kotak prompt
let age = prompt("Masukkan umur Cristiano Ronaldo");

// Menggabungkan beberapa variabel ke dalam satu teks menggunakan template literal
let result = `${firstName} ${lastName} is ${age} years old`;

// Menampilkan hasil gabungan teks melalui alert
alert(result);
