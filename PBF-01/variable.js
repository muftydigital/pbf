// Membuat variabel tanggal dengan var dan nilai awal berupa angka 29
var tanggal = 29;

// Nilai tanggal diubah menjadi teks "30", menunjukkan JavaScript bisa mengganti tipe data sebuah variabel
tanggal = "30";

// Membuat variabel namaBulan menggunakan let dengan nilai awal berupa teks September
let namaBulan = "September";

// Nilai namaBulan kemudian diubah menjadi angka 10
namaBulan = 10;

// Membuat konstanta tahun. Nilai const tidak bisa diisi ulang setelah dibuat
const tahun = "2022";

// Menggabungkan nilai tanggal, namaBulan, dan tahun lalu menampilkannya melalui alert
alert(tanggal + " " + namaBulan + " " + tahun);
